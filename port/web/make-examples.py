#!/usr/bin/env python3
"""Generates examples.js for the playground from files in the repository.

usage: make-examples.py <repo-root> <out-file>
"""
import json
import re
import sys
from pathlib import Path

# (title, path relative to the repository root, extra VCC options)
EXAMPLES = [
    ("Minimum (failing assertion)", "vcc/Docs/Tutorial/c/3.1.min2.c", []),
    ("Minimum with contract", "vcc/Docs/Tutorial/c/3.2.min3.c", []),
    ("Reading through a pointer (failing)", "vcc/Docs/Tutorial/c/01_read_wrong.c", []),
    ("Swap", "vcc/Docs/Tutorial/c/01_swap.c", []),
    ("Integer square root (overflow)", "vcc/Docs/Tutorial/c/02_sqrt_ovf.c", []),
    ("Linear search", "vcc/Docs/Tutorial/c/03_lsearch.c", []),
    ("Binary search", "vcc/Demo/BinarySearch.c", []),
    ("Insertion sort (permutation)", "vcc/Docs/Tutorial/c/04_insertionsort_perm.c", []),
    ("Selection sort", "vcc/Demo/ssort.c", []),
    ("Bit-vector reasoning (parity)", "vcc/Demo/Parity.c", []),
    ("Safe string (data invariant)", "vcc/Docs/Tutorial/c/6.1.safestring.c", []),
    ("Linked list with ghost state", "vcc/Docs/Tutorial/c/7.1.list0.c", []),
    ("Spin lock (concurrency)", "vcc/Docs/Tutorial/c/08_lock.c", []),
    ("Concurrent counter (claims)", "vcc/Docs/Tutorial/c/8.5.counter.c", []),
]


def clean(text: str) -> str:
    # drop the tutorial's /*{name}*/ markers and the test suite's expected-output block
    text = re.sub(r"^/\*\{[^}]*\}\*/\n?", "", text, flags=re.M)
    text = re.split(r"^/\*`", text, maxsplit=1, flags=re.M)[0]
    return text.strip("\n") + "\n"


def main() -> None:
    root = Path(sys.argv[1])
    out = []
    for title, path, args in EXAMPLES:
        out.append({"title": title, "file": Path(path).name, "args": args,
                    "source": clean((root / path).read_text(encoding="utf-8-sig"))})
    Path(sys.argv[2]).write_text(
        "// Generated by port/web/make-examples.py from the repository's tutorial and demos.\n"
        "window.VCC_EXAMPLES = " + json.dumps(out, indent=1) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
